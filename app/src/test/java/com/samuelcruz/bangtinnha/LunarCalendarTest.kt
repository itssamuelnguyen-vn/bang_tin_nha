import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Checks the lunar calendar against values printed by the amlich_vietnam app's Dart implementation (tested there).
 * Each row: solar date, lunar day month year leap, lunar month length, day stem-branch, day star, auspicious,
 * holidays ("|"-separated); spaces in names are written as "_".
 */
class LunarCalendarTest {
    @Test
    fun matchesDart() {
        for (row in FIXTURE) {
            val f = row.split(" ")
            val (y, m, d) = f[0].split("-").map { it.toInt() }
            val lunar = LunarCalendar.solarToLunar(d, m, y)
            val jd = LunarCalendar.jdFromDate(d, m, y)
            val (star, good) = LunarCalendar.dayStar(jd, lunar.month)
            val holidays = LunarCalendar.holidays(d, m, lunar).joinToString("|").replace(' ', '_')
            val actual = listOf(
                f[0], lunar.day, lunar.month, lunar.year, lunar.leap, lunar.monthLength,
                LunarCalendar.canChiDay(jd).replace(' ', '_'), star.replace(' ', '_'), good, holidays,
            ).joinToString(" ").trimEnd()
            assertEquals(row, actual)
        }
    }

